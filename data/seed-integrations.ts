function actions(names: Array<[string, RiskLevel, PermissionLevel]>): IntegrationAction[] {
  return names.map(([name, riskLevel, permissionLevel]) => ({
    id: name.toLowerCase().replaceAll(" ", "-"),
    name,
    riskLevel,
    permissionLevel,
  }));
}

